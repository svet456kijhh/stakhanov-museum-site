const dialog = document.querySelector('#quiz-dialog');
const quizContent = document.querySelector('#quiz-content');
let activeQuiz, questionIndex, score;
document.querySelectorAll('[data-quiz]').forEach(button => button.addEventListener('click', () => {
  activeQuiz = quizzes[button.dataset.quiz];
  questionIndex = 0;
  score = 0;
  document.querySelector('#quiz-title').textContent = activeQuiz.title;
  renderQuestion();
  dialog.showModal();
}));
document.querySelector('.close-quiz').addEventListener('click', () => dialog.close());
dialog.addEventListener('click', event => { if (event.target === dialog) dialog.close(); });
function renderQuestion() {
  quizContent.replaceChildren();
  if (questionIndex === activeQuiz.questions.length) {
    const result = document.createElement('p');
    result.textContent = `Игра окончена! Верных ответов: ${score} из ${activeQuiz.questions.length}. Попробуйте ещё раз или выберите другую игру.`;
    const restart = document.createElement('button');
    restart.className = 'quiz-next';
    restart.textContent = 'Играть ещё раз';
    restart.addEventListener('click', () => { questionIndex = 0; score = 0; renderQuestion(); });
    quizContent.append(result, restart);
    return;
  }
  const [question, choices, correct, explanation] = activeQuiz.questions[questionIndex];
  const progress = document.createElement('p');
  progress.className = 'quiz-progress';
  progress.textContent = `Вопрос ${questionIndex + 1} из ${activeQuiz.questions.length}`;
  const prompt = document.createElement('h3');
  prompt.textContent = question;
  const options = document.createElement('div');
  options.className = 'quiz-options';
  choices.forEach((choice, index) => {
    const option = document.createElement('button');
    option.type = 'button';
    option.textContent = choice;
    option.addEventListener('click', () => {
      if (index === correct) score++;
      [...options.children].forEach((item, i) => {
        item.disabled = true;
        if (i === correct) item.classList.add('correct');
        else if (i === index) item.classList.add('wrong');
      });
      const feedback = document.createElement('p');
      feedback.className = 'quiz-feedback';
      feedback.textContent = `${index === correct ? 'Верно! ' : 'Пока нет. '}${explanation}`;
      const next = document.createElement('button');
      next.className = 'quiz-next';
      next.textContent = questionIndex + 1 === activeQuiz.questions.length ? 'Узнать результат' : 'Следующий вопрос →';
      next.addEventListener('click', () => { questionIndex++; renderQuestion(); });
      quizContent.append(feedback, next);
      next.focus();
    });
    options.append(option);
  });
  quizContent.append(progress, prompt, options);
}
